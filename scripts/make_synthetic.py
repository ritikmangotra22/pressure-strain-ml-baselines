"""Generate SYNTHETIC files in the Lee & Moser layout, for testing the code only.

!! These are NOT DNS data. Nothing computed from them may be reported. !!
The profiles are smooth analytic shapes chosen only so that the pipeline's
consistency checks (k = trace/2, budget balance, dU/dy) are exercised and a
learnable relation between features and targets exists.
"""
import argparse
from pathlib import Path

import numpy as np

HEADER = "% SYNTHETIC TEST DATA - NOT DNS - generated by make_synthetic.py for code testing only\n"


def profiles(re_tau, n, rng):
    eta_g = np.linspace(0, 1, n)
    yd = 1 - np.tanh(2.5 * (1 - eta_g)) / np.tanh(2.5)        # wall-clustered, y/delta in [0,1)
    yd = yd[:-1]                                              # centreline not stored, as in LM files
    yp = yd * re_tau
    kap, B = 0.384, 7.8
    U = np.log(1 + kap * yp) / kap + B * (1 - np.exp(-yp / 11) - yp / 11 * np.exp(-yp / 3))
    dU = 1 / (1 + kap * yp) + B * (np.exp(-yp / 11) / 11 - np.exp(-yp / 3) / 11 + yp / 33 * np.exp(-yp / 3))
    f = lambda a, c: a * (1 - np.exp(-yp / c)) ** 2
    uu = 7.5 * (yp / 15) ** 2 * np.exp(1 - (yp / 15) ** 2 * 0.5) * 0 + f(1.0, 8) * (4 + 4 * np.exp(-yp / 40)) * (1 - 0.6 * yd)
    vv = f(1.0, 25) * 1.1 * (1 - 0.5 * yd)
    ww = f(1.0, 15) * 1.6 * (1 - 0.5 * yd)
    uv = -f(1.0, 18) * (1 - yd)
    k = 0.5 * (uu + vv + ww)
    eps = 0.02 + 0.15 * np.exp(-yp / 12) + 0.3 / (1 + 0.4 * yp)
    return yd, yp, U, dU, uu, vv, ww, uv, k, eps


def write(path, cols):
    arr = np.column_stack(cols)
    with open(path, "w") as fh:
        fh.write(HEADER)
        np.savetxt(fh, arr, fmt="%.15e")


def main(out, seed):
    rng = np.random.default_rng(seed)
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    for re_tau, n in [(180, 97), (550, 193), (1000, 257), (2000, 385), (5200, 769)]:
        yd, yp, U, dU, uu, vv, ww, uv, k, eps = profiles(re_tau, n, rng)
        with np.errstate(divide="ignore", invalid="ignore"):
            b11, b22, b12 = uu / (2 * k) - 1 / 3, vv / (2 * k) - 1 / 3, uv / (2 * k)
            eta = np.nan_to_num(k * dU / eps)
        b11, b22, b12 = (np.nan_to_num(a) for a in (b11, b22, b12))
        # An arbitrary smooth, learnable "pressure strain" with zero trace + small noise.
        p11 = (-3.0 * b11 - 0.25 * b12 * eta) * eps
        p22 = (-3.0 * b22 + 0.15 * b12 * eta) * eps
        p33 = -(p11 + p22)
        p12 = (-3.0 * b12 + 0.4 * eta * (1 / 3 + b22) * 0.5) * eps
        noise = lambda a: a * (1 + 0.01 * rng.standard_normal(a.shape))
        ps = {"uu": noise(p11), "vv": noise(p22), "ww": p33, "uv": noise(p12), "k": 0 * eps}
        prod = {"uu": -2 * uv * dU, "vv": 0 * yp, "ww": 0 * yp, "uv": -vv * dU, "k": -uv * dU}
        diss = {"uu": 2 / 3 * eps, "vv": 2 / 3 * eps, "ww": 2 / 3 * eps, "uv": 0 * eps, "k": eps}
        for c in ("uu", "vv", "ww", "uv", "k"):
            vt = 0.01 * np.exp(-yp / 5) * eps
            pt = 0 * yp if c in ("uu", "k") else 0.02 * np.exp(-yp / 10) * eps
            tt = -(prod[c] + vt + ps[c] + pt - diss[c])
            bal = prod[c] + tt + vt + ps[c] + pt - diss[c]
            write(out / f"LM_Channel_{re_tau:04d}_RSTE_{c}_prof.dat", [yd, yp, prod[c], tt, vt, ps[c], pt, diss[c], bal])
        write(out / f"LM_Channel_{re_tau:04d}_mean_prof.dat", [yd, yp, U, dU, 0 * yp, 0 * yp])
        write(out / f"LM_Channel_{re_tau:04d}_vel_fluc_prof.dat", [yd, yp, uu, vv, ww, uv, 0 * yp, 0 * yp, k])
    print(f"Wrote SYNTHETIC test files to {out}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    main(a.out, a.seed)
